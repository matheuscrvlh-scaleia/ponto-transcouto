-- =====================================================================
-- 009 — Grupos de permissão (Configuração → Permissões).
-- Cada empresa cria os seus grupos e escolhe as telas liberadas para
-- cada um. O alcance do grupo define as unidades que o usuário vê:
--   'empresa'  = todas as unidades da empresa (o antigo perfil RH);
--   'unidades' = só as unidades vinculadas a ele (o antigo gestor).
-- RH e Gestor viram os grupos padrão de cada empresa (editáveis).
-- clientes.perfil continua existindo, derivado do alcance do grupo,
-- para o escopo (unidades_permitidas) e o código que já usa o perfil.
-- A equipe Scale IA (usuarios) não tem grupo: acesso total.
-- =====================================================================

CREATE TABLE public.grupos_permissao (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     integer     NOT NULL REFERENCES public.empresas(id) ON DELETE CASCADE,
    nome           text        NOT NULL,
    descricao      text,
    alcance        text        NOT NULL DEFAULT 'unidades',
    telas          text[]      NOT NULL DEFAULT '{}',
    -- grupos criados pelo sistema para cada empresa ('rh' / 'gestor'); NULL = criado pelo cliente
    padrao         text,
    criado_em      timestamptz NOT NULL DEFAULT now(),
    atualizado_em  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT grupos_alcance_chk   CHECK (alcance IN ('empresa', 'unidades')),
    CONSTRAINT grupos_padrao_chk    CHECK (padrao IS NULL OR padrao IN ('rh', 'gestor')),
    CONSTRAINT grupos_nome_chk      CHECK (length(btrim(nome)) BETWEEN 2 AND 60),
    CONSTRAINT grupos_descricao_chk CHECK (descricao IS NULL OR length(descricao) <= 300),
    -- telas do catálogo (server/src/types/permissoes.types.ts)
    CONSTRAINT grupos_telas_chk     CHECK (telas <@ ARRAY['dashboard', 'batidas', 'colaboradores', 'usuarios', 'permissoes',
                                                          'integracao', 'atualizacao', 'unidades', 'alertas', 'fechamentos']::text[]),
    CONSTRAINT grupos_id_empresa_uk UNIQUE (id, empresa_id)
);
CREATE UNIQUE INDEX grupos_nome_uk   ON public.grupos_permissao (empresa_id, lower(nome));
CREATE UNIQUE INDEX grupos_padrao_uk ON public.grupos_permissao (empresa_id, padrao) WHERE padrao IS NOT NULL;

CREATE TRIGGER trg_grupos_permissao_atualizado_em
    BEFORE UPDATE ON public.grupos_permissao
    FOR EACH ROW EXECUTE FUNCTION public.definir_atualizado_em();

-- ---------------------------------------------------------------------
-- Grupos padrão de cada empresa (as que existem e as que forem criadas)
-- ---------------------------------------------------------------------
CREATE FUNCTION public.criar_grupos_padrao(p_empresa_id integer)
RETURNS void
LANGUAGE sql
VOLATILE
SET search_path = public, pg_catalog
AS $$
    INSERT INTO grupos_permissao (empresa_id, nome, descricao, alcance, telas, padrao)
    VALUES
        (p_empresa_id, 'RH',
         'Cuida da empresa toda: usuários, permissões, unidades, alertas, atualização dos dados e fechamentos.',
         'empresa',
         ARRAY['dashboard', 'batidas', 'colaboradores', 'usuarios', 'permissoes', 'integracao', 'atualizacao',
               'unidades', 'alertas', 'fechamentos'],
         'rh'),
        (p_empresa_id, 'Gestor',
         'Acompanha o banco de horas das unidades vinculadas a ele e pode pedir nova extração dos dados delas.',
         'unidades',
         ARRAY['dashboard', 'batidas', 'colaboradores', 'integracao'],
         'gestor')
    ON CONFLICT DO NOTHING
$$;

SELECT public.criar_grupos_padrao(id) FROM public.empresas;

CREATE FUNCTION public.empresa_grupos_padrao()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
BEGIN
    PERFORM criar_grupos_padrao(NEW.id);
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_empresas_grupos_padrao
    AFTER INSERT ON public.empresas
    FOR EACH ROW EXECUTE FUNCTION public.empresa_grupos_padrao();

-- ---------------------------------------------------------------------
-- clientes.grupo_id (os atuais entram no grupo padrão do perfil)
-- ---------------------------------------------------------------------
ALTER TABLE public.clientes ADD COLUMN grupo_id integer;

UPDATE public.clientes c
   SET grupo_id = g.id
  FROM public.grupos_permissao g
 WHERE g.empresa_id = c.empresa_id AND g.padrao = c.perfil;

ALTER TABLE public.clientes
    ALTER COLUMN grupo_id SET NOT NULL,
    ADD CONSTRAINT clientes_grupo_fk FOREIGN KEY (grupo_id, empresa_id)
        REFERENCES public.grupos_permissao (id, empresa_id) ON DELETE RESTRICT;
CREATE INDEX clientes_grupo_idx ON public.clientes (grupo_id);

-- Mantém perfil e grupo coerentes:
-- - sem grupo (ou trocando de empresa sem trocar o grupo): entra no grupo padrão do perfil;
-- - mudou só o perfil (código antigo, seeds): vai para o grupo padrão do novo perfil;
-- - em todo caso o perfil é o do alcance do grupo ('empresa' → rh, 'unidades' → gestor).
CREATE FUNCTION public.sincronizar_perfil_cliente()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
    v_perfil_grupo text;
BEGIN
    IF NEW.grupo_id IS NULL
       OR (TG_OP = 'UPDATE' AND NEW.empresa_id <> OLD.empresa_id AND NEW.grupo_id = OLD.grupo_id) THEN
        SELECT id INTO NEW.grupo_id FROM grupos_permissao WHERE empresa_id = NEW.empresa_id AND padrao = NEW.perfil;
    ELSIF TG_OP = 'UPDATE' AND NEW.grupo_id = OLD.grupo_id AND NEW.perfil IS DISTINCT FROM OLD.perfil THEN
        SELECT CASE alcance WHEN 'empresa' THEN 'rh' ELSE 'gestor' END INTO v_perfil_grupo
          FROM grupos_permissao WHERE id = NEW.grupo_id;
        IF NEW.perfil <> v_perfil_grupo THEN
            SELECT id INTO NEW.grupo_id FROM grupos_permissao WHERE empresa_id = NEW.empresa_id AND padrao = NEW.perfil;
        END IF;
    END IF;

    SELECT CASE alcance WHEN 'empresa' THEN 'rh' ELSE 'gestor' END INTO NEW.perfil
      FROM grupos_permissao WHERE id = NEW.grupo_id;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_clientes_perfil_grupo
    BEFORE INSERT OR UPDATE OF grupo_id, empresa_id, perfil ON public.clientes
    FOR EACH ROW EXECUTE FUNCTION public.sincronizar_perfil_cliente();

-- grupo mudou de alcance: o perfil dos usuários dele acompanha
CREATE FUNCTION public.propagar_alcance_grupo()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
BEGIN
    UPDATE clientes
       SET perfil = CASE NEW.alcance WHEN 'empresa' THEN 'rh' ELSE 'gestor' END
     WHERE grupo_id = NEW.id;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_grupos_alcance
    AFTER UPDATE OF alcance ON public.grupos_permissao
    FOR EACH ROW WHEN (NEW.alcance IS DISTINCT FROM OLD.alcance)
    EXECUTE FUNCTION public.propagar_alcance_grupo();

