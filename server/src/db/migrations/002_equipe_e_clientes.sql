-- ---------------------------------------------------------------------
ALTER TABLE public.clientes         ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cliente_unidades ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        EXECUTE 'REVOKE ALL ON public.clientes, public.cliente_unidades FROM anon, authenticated';
        EXECUTE 'REVOKE ALL ON FUNCTION public.unidades_permitidas(text, integer) FROM anon, authenticated';
        EXECUTE 'REVOKE ALL ON FUNCTION public.garantir_login_unico() FROM anon, authenticated';
    END IF;
END $$;
