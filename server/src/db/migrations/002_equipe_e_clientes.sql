-- ---------------------------------------------------------------------
-- 6. Um mesmo e-mail/CPF não pode existir nas duas tabelas (login único)
-- ---------------------------------------------------------------------
CREATE FUNCTION public.garantir_login_unico()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
DECLARE
    v_outra text := CASE WHEN TG_TABLE_NAME = 'usuarios' THEN 'clientes' ELSE 'usuarios' END;
    v_existe boolean;
BEGIN
    EXECUTE format(
        'SELECT EXISTS (SELECT 1 FROM public.%I WHERE ($1 IS NOT NULL AND lower(email) = lower($1))
                                               OR ($2 IS NOT NULL AND cpf = $2))', v_outra)
       INTO v_existe
      USING NEW.email, NEW.cpf;
    IF v_existe THEN
        RAISE EXCEPTION 'E-mail ou CPF já usado em %', v_outra USING ERRCODE = 'unique_violation';
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER trg_usuarios_login_unico
    BEFORE INSERT OR UPDATE OF email, cpf ON public.usuarios
    FOR EACH ROW EXECUTE FUNCTION public.garantir_login_unico();
CREATE TRIGGER trg_clientes_login_unico
    BEFORE INSERT OR UPDATE OF email, cpf ON public.clientes
    FOR EACH ROW EXECUTE FUNCTION public.garantir_login_unico();

REVOKE EXECUTE ON FUNCTION public.garantir_login_unico() FROM PUBLIC;

