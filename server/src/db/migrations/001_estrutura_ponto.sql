-- 3.1 CPF: canonizar para 11 dígitos em texto (hoje pode estar como número)
DO $$
DECLARE
    v_tipo text;
BEGIN
    SELECT data_type INTO v_tipo
      FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'usuarios' AND column_name = 'cpf';

    IF v_tipo IN ('integer', 'bigint', 'numeric') THEN
        ALTER TABLE public.usuarios ALTER COLUMN cpf TYPE varchar(11)
            USING CASE WHEN cpf IS NULL THEN NULL
                       WHEN length(cpf::text) <= 11 THEN lpad(cpf::text, 11, '0')
                       ELSE cpf::text END;          -- >11 falha no cast: revisar manualmente
    ELSIF v_tipo IS NOT NULL THEN
        UPDATE public.usuarios
           SET cpf = NULLIF(regexp_replace(cpf, '[^0-9]', '', 'g'), '')
         WHERE cpf IS NOT NULL;
        ALTER TABLE public.usuarios ALTER COLUMN cpf TYPE varchar(11);
    END IF;
END $$;

