-- ---------------------------------------------------------------------
-- 15. Escopo de acesso (usado pela API em toda leitura)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.unidades_permitidas(p_usuario_id integer)
RETURNS SETOF integer
LANGUAGE sql
STABLE
SET search_path = public, pg_catalog
AS $$
    SELECT un.id
      FROM usuarios u
      JOIN unidades un
        ON u.perfil = 'admin'
        OR (u.perfil = 'rh' AND un.empresa_id = u.empresa_id)
     WHERE u.id = p_usuario_id AND u.ativo AND un.ativo
    UNION
    SELECT uu.unidade_id
      FROM usuarios u
      JOIN usuario_unidades uu ON uu.usuario_id = u.id
      JOIN unidades un         ON un.id = uu.unidade_id AND un.ativo AND un.nome_exibicao IS NOT NULL
     WHERE u.id = p_usuario_id AND u.ativo AND u.perfil = 'gestor'
$$;

