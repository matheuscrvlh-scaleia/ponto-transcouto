-- Congelamento: fechamento publicado não muda (reabrir = mudar status antes)
CREATE OR REPLACE FUNCTION public.impedir_alteracao_publicado()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_catalog
AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.fechamentos f
                WHERE f.id = OLD.fechamento_id AND f.status = 'sucesso') THEN
        RAISE EXCEPTION 'registros_horas: fechamento % já publicado (congelado)', OLD.fechamento_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_registros_horas_congelado
    BEFORE UPDATE OR DELETE ON public.registros_horas
    FOR EACH ROW EXECUTE FUNCTION public.impedir_alteracao_publicado();

